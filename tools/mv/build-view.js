import * as THREE from 'three';
import {GLTFLoader} from 'three/examples/jsm/loaders/GLTFLoader.js';
import {MeshoptDecoder} from 'three/examples/jsm/libs/meshopt_decoder.module.js';
import {RoomEnvironment} from 'three/examples/jsm/environments/RoomEnvironment.js';
import {BUILDERS, materials} from '../../src/ships/build.js';
const q = new URLSearchParams(location.search);
const W = 1200, H = 900;
const renderer = new THREE.WebGLRenderer({antialias: true});
renderer.setSize(W, H);
renderer.toneMapping = THREE.ACESFilmicToneMapping;
renderer.outputColorSpace = THREE.SRGBColorSpace;
document.body.style.margin = '0';
document.body.appendChild(renderer.domElement);
const scene = new THREE.Scene();
scene.background = new THREE.Color(0x15181d);
const pm = new THREE.PMREMGenerator(renderer);
scene.environment = pm.fromScene(new RoomEnvironment(), 0.04).texture;
scene.environmentIntensity = 0.7;
const sun = new THREE.DirectionalLight(0xffffff, 2.2);
sun.position.set(5, 8, 6);
scene.add(sun);
const loader = new GLTFLoader();
loader.setMeshoptDecoder(MeshoptDecoder);
const loadNasa = (n) => new Promise((res, rej) => loader.load(`/${n}.glb`, (g) => res(g.scene), undefined, rej));
(async () => {
  materials();
  const root = await BUILDERS[q.get('b')](loadNasa);
  scene.add(root);
  const box = new THREE.Box3().setFromObject(root);
  const size = box.getSize(new THREE.Vector3());
  const c = box.getCenter(new THREE.Vector3());
  const r = size.length() / 2;
  const views = q.get('one') ? [[+q.get('az') || 35, +q.get('el') || 15]] : [[0, 0], [35, 15], [90, 0], [200, 25]];
  const cam = new THREE.PerspectiveCamera(26, 1, r / 100, r * 100);
  renderer.setScissorTest(true);
  views.forEach(([az, el], k) => {
    const one = views.length === 1;
    const vw = one ? W : W / 2, vh = one ? H : H / 2;
    const x = one ? 0 : (k % 2) * W / 2, y = one ? 0 : (1 - Math.floor(k / 2)) * H / 2;
    const zoom = +q.get('zoom') || 1;
    const a = THREE.MathUtils.degToRad(az), e = THREE.MathUtils.degToRad(el);
    const d = r / Math.sin(THREE.MathUtils.degToRad(13)) / zoom;
    const t = c.clone();
    if (q.get('ty')) t.y = +q.get('ty');
    cam.position.set(t.x + d * Math.cos(e) * Math.sin(a), t.y + d * Math.sin(e), t.z + d * Math.cos(e) * Math.cos(a));
    cam.aspect = vw / vh; cam.updateProjectionMatrix();
    cam.lookAt(t);
    renderer.setViewport(x, y, vw, vh);
    renderer.setScissor(x, y, vw, vh);
    renderer.render(scene, cam);
  });
  let tris = 0;
  root.traverse((o) => { if (o.isMesh) tris += o.geometry.index ? o.geometry.index.count / 3 : o.geometry.attributes.position.count / 3; });
  window.STATS = {size: size.toArray().map((v) => +v.toFixed(2)), center: c.toArray().map((v) => +v.toFixed(2)), tris: Math.round(tris)};
  window.DONE = true;
})().catch((e) => { window.STATS = {error: String(e.stack || e)}; window.DONE = true; });
